#!/usr/bin/env python3
"""Bake Fusion Pixel glyphs used by the workbench into workbench/js/core/.

    python3 tools/build-font.py --ext NAME
        Glyphs that the text table content/i18n-NAME/*.json needs and the frozen
        fonts lack go into workbench/js/core/font-NAME.js. That file only adds
        missing glyphs at load time (never replaces one), so nothing already drawn
        changes. Use this for new UI text (content/i18n-delivery, content/i18n-extra).

    python3 tools/build-font.py --rebuild-frozen
        Rewrites font-data.js (12px, menus and titles) and font-small.js (10px,
        dialogue bubbles). font-data.js feeds the content hash of every procedural
        asset and font-small.js that of the screens with bubbles: rewriting them
        makes approved screens stale (AGENTS.md 2a). Art lead only, on request.

Development tool only (needs Pillow); the browser and tools/art.mjs read the
generated files.
"""
import argparse, hashlib, json, re, sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "third_party/fonts/fusion-pixel-12px/fusion-pixel-12px-proportional-zh_hans.otf.woff2"
OUT = ROOT / "workbench/js/core/font-data.js"
SMALL = ROOT / "third_party/fonts/fusion-pixel-10px/fusion-pixel-10px-proportional-sc.woff2"
SMALL_OUT = ROOT / "workbench/js/core/font-small.js"
BIG_SPEC = (FONT, 12, 14, 11)       # font, size, line height, baseline
SMALL_SPEC = (SMALL, 10, 12, 10)

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument("--ext", metavar="NAME", help="bake the glyphs content/i18n-NAME needs into workbench/js/core/font-NAME.js")
ap.add_argument("--rebuild-frozen", action="store_true", help="rewrite font-data.js and font-small.js (makes approved screens stale)")
args = ap.parse_args()


def existing(path):
    if not path.exists():
        return set()
    m = re.search(r"glyphs: (\{.*\})\};", path.read_text(encoding="utf-8"))
    return set(json.loads(m.group(1)).keys()) if m else set()


def bake_glyphs(spec, charset):
    font_path, size, height, baseline = spec
    font = ImageFont.truetype(str(font_path), size)
    glyphs = {}
    for ch in sorted(charset):
        adv = max(1, round(font.getlength(ch)))
        img = Image.new("1", (adv, height))
        ImageDraw.Draw(img).text((0, baseline), ch, font=font, fill=1, anchor="ls")
        rows = [sum(1 << x for x in range(adv) if img.getpixel((x, y))) for y in range(height)]
        glyphs[ch] = [adv] + rows
    return glyphs


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def strings(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for v in value.values():
            yield from strings(v)


if args.ext:
    name = args.ext
    if not re.fullmatch(r"[a-z0-9_-]+", name) or name in ("data", "small"):
        sys.exit("--ext: use the text table's name, e.g. delivery (content/i18n-delivery)")
    table_dir = ROOT / f"content/i18n-{name}"
    files = sorted(table_dir.glob("*.json"))
    if not files:
        sys.exit(f"no text tables in {table_dir.relative_to(ROOT)}")
    need = set()
    for path in files:
        for k, v in json.loads(path.read_text(encoding="utf-8")).items():
            if k == "_meta":
                continue
            for s in strings(v):
                need.update(c for c in s if not c.isspace())
    big = bake_glyphs(BIG_SPEC, need - existing(OUT))
    small = bake_glyphs(SMALL_SPEC, need - existing(SMALL_OUT))
    out = ROOT / f"workbench/js/core/font-{name}.js"
    dump = lambda g: json.dumps(g, ensure_ascii=False, separators=(",", ":"))
    out.write_text(
        f"/* Generated by `python3 tools/build-font.py --ext {name}` from Fusion Pixel 12px and 10px (OFL, third_party/fonts/).\n"
        f" * Glyphs that content/i18n-{name} needs and the frozen fonts (font-data.js, font-small.js) lack.\n"
        " * Adds missing glyphs only, never replaces one, so nothing already drawn changes. Do not edit by hand.\n"
        f" * Source fonts SHA-256: 12px {digest(FONT)}, 10px {digest(SMALL)}. */\n"
        "(function (root) {\n  const PB = (root.PB = root.PB || {});\n"
        "  const add = (font, glyphs) => { if (font) for (const ch of Object.keys(glyphs)) if (!(ch in font.glyphs)) font.glyphs[ch] = glyphs[ch]; };\n"
        f"  add(PB.FONT, {dump(big)});\n"
        f"  add(PB.FONT_SMALL, {dump(small)});\n"
        "})(typeof window !== \"undefined\" ? window : globalThis);\n",
        encoding="utf-8",
    )
    print(f"{len(big)} glyphs (12px) + {len(small)} glyphs (10px) -> {out.relative_to(ROOT)}")
    sys.exit(0)

if not args.rebuild_frozen:
    sys.exit("font-data.js and font-small.js are frozen (they feed approved screens' content hashes).\n"
             "New text: put it in content/i18n-<name>/ and run  python3 tools/build-font.py --ext <name>\n"
             "Rewriting the frozen fonts (art lead only, makes approved screens stale): --rebuild-frozen")

# Every character any text may use (the 10px dialogue font gets all of them).
chars = set(chr(i) for i in range(32, 127))
for path in list((ROOT / "workbench/js/core").glob("*.js")) + list((ROOT / "content/levels").rglob("*.json")) + list((ROOT / "art/source").rglob("*.json")) + list((ROOT / "content/i18n").glob("*.json")):
    if path.name.startswith("font-"):
        continue
    chars.update(c for c in path.read_text(encoding="utf-8") if ord(c) > 127 and not c.isspace())

# The 12px set is append-only: font-data.js is part of every procedural asset's
# content hash, so it only grows when a 12px string (menus, titles, name tags)
# needs a new character. Dialogue text ("dlg.*", level hints) is drawn in 10px.
big = existing(OUT) | set(chr(i) for i in range(32, 127))
for path in (ROOT / "content/i18n").glob("*.json"):
    for k, v in json.loads(path.read_text(encoding="utf-8")).items():
        if isinstance(v, str) and not k.startswith("dlg.") and ".hint." not in k:
            big.update(c for c in v if not c.isspace())


def bake(spec, out, var, label, charset):
    font_path, size, height, baseline = spec
    glyphs = bake_glyphs(spec, charset)
    out.write_text(
        f"/* Generated by tools/build-font.py from {label} (OFL, third_party/fonts/).\n"
        " * Source font SHA-256: " + digest(font_path) + ". Do not edit by hand. */\n"
        "(function (root) {\n  const PB = (root.PB = root.PB || {});\n"
        f"  PB.{var} = {{height: {height}, baseline: {baseline}, glyphs: " + json.dumps(glyphs, ensure_ascii=False, separators=(",", ":")) + "};\n"
        "})(typeof window !== \"undefined\" ? window : globalThis);\n",
        encoding="utf-8",
    )
    print(f"{len(glyphs)} glyphs -> {out.relative_to(ROOT)}")


bake(BIG_SPEC, OUT, "FONT", "Fusion Pixel 12px", big)
bake(SMALL_SPEC, SMALL_OUT, "FONT_SMALL", "Fusion Pixel 10px", chars | big)
